static void test_pack(void)
{
    zip_entry_t entries[8];
    int count = Zip_List(pack, sizeof(pack), entries, 8);
    CHECK(count == 2, "the pack lists %d files, not 2 (the folder left out)", count);
    CHECK(Zip_List(pack, 40, entries, 8) < 0, "a cut-off pack reads as a ZIP");
    const zip_entry_t *info = NULL, *sound = NULL;
    for (int i = 0; i < count; ++i)
    {
	if (!strcmp(entries[i].name, "SNDINFO")) info = &entries[i];
	if (!strcmp(entries[i].name, "sounds/DSTEST.wav")) sound = &entries[i];
    }
    CHECK(info && sound, "the pack's SNDINFO or sound is missing");
    if (!info || !sound) return;
    CHECK(sound->method == 8 && info->method == 0, "methods %d and %d, not deflated and stored", sound->method, info->method);

    size_t length = 0;
    unsigned char *text = Zip_Read(pack, sizeof(pack), info, &length);
    CHECK(text && length == info->size, "the stored SNDINFO doesn't read");
    sndinfo_t *names = SndInfo_New();
    CHECK(SndInfo_Parse(names, (const char *)text, length) == 4, "SNDINFO gives %d names, not 4", SndInfo_Count(names));
    unsigned seed = 1;
    const char *pain = SndInfo_Resolve(names, "IMP/PAIN", &seed);
    CHECK(pain && !strcmp(pain, "DSTEST"), "imp/pain is %s", pain ? pain : "(none)");
    int saw_a = 0, saw_b = 0;
    for (int i = 0; i < 64; ++i)
    {
	const char *sight = SndInfo_Resolve(names, "imp/sight", &seed);
	saw_a += sight && !strcmp(sight, "DSA");
	saw_b += sight && !strcmp(sight, "DSB");
    }
    CHECK(saw_a && saw_b && saw_a + saw_b == 64, "the $random set picked DSA %d and DSB %d times of 64", saw_a, saw_b);
    CHECK(!SndInfo_Resolve(names, "imp/death", &seed), "an undefined name resolves");
    free(text);

    unsigned char *wav = Zip_Read(pack, sizeof(pack), sound, &length);
    CHECK(wav && length == sound->size, "the deflated sound doesn't inflate");
    float *mono = NULL;
    int frames = 0, rate = 0;
    CHECK(wav && Track_DecodeMemory(wav, length, &mono, &frames, &rate), "the WAV doesn't decode");
    CHECK(frames == 200 && rate == 22050, "%d frames at %d Hz, not 200 at 22050", frames, rate);
    for (int i = 0; mono && i < frames; ++i)
	if (fabsf(mono[i] - (float)(int)(16000 * sin(i * 0.3)) / 32768.0f) > 1e-3f)
	{
	    CHECK(0, "sample %d is %f", i, mono[i]);
	    break;
	}
    unsigned char junk[64] = "not a sound at all, nor anything like one";
    CHECK(!Track_DecodeMemory(junk, sizeof(junk), &mono, &frames, &rate) || frames == 0, "junk decodes as a sound");
    free(mono);
    free(wav);
    SndInfo_Free(names);
}

/* What a sound pack's SNDINFO holds, line by line: comments, quoting, sets
   over lines, aliases, skipped commands, and a later definition winning. */
static void test_sndinfo(void)
{
    static const char text[] =
	"// Generic Sounds --------\n"
	"claw1\t\t\t\t\tdsclaw1\n"
	"claw2 dsclaw2 // the second\n"
	"/* a block\n comment */ fireshooty1 \"DSFIRSH1\"\n"
	"$random imp/melee\n{ claw1\n claw2 }\n"
	"$playeralias player male *gibbed pl_gibbed\n"
	"$limit imp/melee 2\n"
	"$alias imp/attack fireshooty1\n"
	"$random menu/quit1 { a b c }\n"
	"imp/pain DSPOPAIN\n";
    sndinfo_t *names = SndInfo_New();
    SndInfo_Parse(names, text, sizeof(text) - 1);
    unsigned seed = 7;
    const char *melee = SndInfo_Resolve(names, "imp/melee", &seed);
    CHECK(melee && (!strcmp(melee, "DSCLAW1") || !strcmp(melee, "DSCLAW2")), "imp/melee is %s", melee ? melee : "(none)");
    const char *attack = SndInfo_Resolve(names, "imp/attack", &seed);
    CHECK(attack && !strcmp(attack, "DSFIRSH1"), "imp/attack is %s", attack ? attack : "(none)");
    CHECK(!SndInfo_Resolve(names, "player", &seed) && !SndInfo_Resolve(names, "$limit", &seed), "a skipped command defined a name");
    /* A loose SNDINFO read after the pack's changes what it says. */
    static const char later[] = "imp/pain DSBGPAI2\n";
    SndInfo_Parse(names, later, sizeof(later) - 1);
    const char *pain = SndInfo_Resolve(names, "imp/pain", &seed);
    CHECK(pain && !strcmp(pain, "DSBGPAI2"), "imp/pain after the later SNDINFO is %s", pain ? pain : "(none)");
    SndInfo_Free(names);
}

int main(void)
{
    test_pack();
    test_sndinfo();
    if (failures) { fprintf(stderr, "%d failures\n", failures); return 1; }
    puts("user sounds: ok");
    return 0;
}
